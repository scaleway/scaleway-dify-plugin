#!/usr/bin/env python3
"""Generate the plugin's model YAML files from models.dev.

Every Scaleway model listed in models.dev is generated, with its type, context
size, max output, capabilities and price.

Usage (from the plugin folder):
    python scripts/sync_models.py --dry-run
    python scripts/sync_models.py
"""

import argparse
import json
import sys
import urllib.request
from pathlib import Path

import yaml

MODELS_DEV_URL = "https://models.dev/api.json?type=all"
MODELS_DEV_PROVIDER = "scaleway"
GENERATED_HEADER = "# Generated by scripts/sync_models.py from models.dev. Do not edit by hand.\n"

# models.dev "type" -> (Dify model type, folder under models/)
MODEL_TYPES = {
    None: ("llm", "llm"),
    "chat": ("llm", "llm"),
    "embedding": ("text-embedding", "text_embedding"),
    "transcription": ("speech2text", "speech2text"),
}

DEFAULT_MAX_TOKENS = 4096
EMBEDDING_MAX_CHUNKS = 32
# From Scaleway's Audio Transcriptions API reference and supported-models page.
STT_FILE_UPLOAD_LIMIT_MB = 25
STT_FILE_EXTENSIONS = "wav,mp3,flac,mpga,oga,ogg"


def load_catalog(path: str | None) -> dict:
    if path:
        return json.loads(Path(path).read_text())
    request = urllib.request.Request(MODELS_DEV_URL, headers={"User-Agent": "dify-scaleway-plugin"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def price(value: float) -> str:
    return f"{value:.6f}".rstrip("0").rstrip(".") or "0"


def pricing(meta: dict, with_output: bool) -> dict | None:
    cost = meta.get("cost")
    if not cost or "input" not in cost:
        return None
    # models.dev publishes prices in USD per million tokens (Scaleway bills in EUR).
    block = {"input": price(cost["input"])}
    if with_output:
        block["output"] = price(cost.get("output", 0))
    block.update({"unit": "0.000001", "currency": "USD"})
    return block


def llm_yaml(model_id: str, meta: dict) -> dict:
    inputs = meta.get("modalities", {}).get("input", [])
    max_output = meta["limit"]["output"]

    features = []
    if meta.get("tool_call"):
        features += ["agent-thought", "tool-call", "multi-tool-call", "stream-tool-call"]
    if "image" in inputs:
        features.append("vision")
    if meta.get("structured_output"):
        features.append("structured-output")

    rules: list[dict] = []
    if meta.get("temperature", True):
        rules.append({"name": "temperature", "use_template": "temperature"})
    rules += [
        {"name": "top_p", "use_template": "top_p"},
        {"name": "presence_penalty", "use_template": "presence_penalty"},
        {
            "name": "max_tokens",
            "use_template": "max_tokens",
            "default": min(DEFAULT_MAX_TOKENS, max_output),
            "min": 1,
            "max": max_output,
        },
    ]
    for option in meta.get("reasoning_options") or []:
        if option.get("type") == "effort" and option.get("values"):
            rules.append(
                {
                    "name": "reasoning_effort",
                    "label": {"en_US": "Reasoning Effort"},
                    "type": "string",
                    "required": False,
                    "options": option["values"],
                    "help": {"en_US": "How much the model reasons before answering. Leave unset for its default."},
                }
            )
    if meta.get("structured_output"):
        rules += [
            {
                "name": "response_format",
                "label": {"en_US": "Response Format"},
                "type": "string",
                "required": False,
                "options": ["text", "json_object", "json_schema"],
                "help": {"en_US": "Specifies the format the model must output"},
            },
            {"name": "json_schema", "use_template": "json_schema"},
        ]

    data = {
        "model": model_id,
        "label": {"en_US": meta.get("name", model_id)},
        "model_type": "llm",
        "features": features,
        "model_properties": {"mode": "chat", "context_size": meta["limit"]["context"]},
        "parameter_rules": rules,
    }
    if block := pricing(meta, with_output=True):
        data["pricing"] = block
    return data


def embedding_yaml(model_id: str, meta: dict) -> dict:
    data = {
        "model": model_id,
        "label": {"en_US": meta.get("name", model_id)},
        "model_type": "text-embedding",
        "model_properties": {"context_size": meta["limit"]["context"], "max_chunks": EMBEDDING_MAX_CHUNKS},
    }
    if block := pricing(meta, with_output=False):
        data["pricing"] = block
    return data


def speech2text_yaml(model_id: str, meta: dict) -> dict:
    # No pricing: Scaleway bills audio per minute, which Dify's model files can't express.
    return {
        "model": model_id,
        "label": {"en_US": meta.get("name", model_id)},
        "model_type": "speech2text",
        "model_properties": {
            "file_upload_limit": STT_FILE_UPLOAD_LIMIT_MB,
            "supported_file_extensions": STT_FILE_EXTENSIONS,
        },
    }


BUILDERS = {"llm": llm_yaml, "text-embedding": embedding_yaml, "speech2text": speech2text_yaml}


def dump(data: dict) -> str:
    return GENERATED_HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--plugin-dir", default=Path(__file__).resolve().parent.parent, type=Path)
    parser.add_argument("--models-dev-json", help="Saved models.dev api.json, instead of downloading it")
    parser.add_argument("--dry-run", action="store_true", help="Show what would change without writing files")
    args = parser.parse_args()

    known = load_catalog(args.models_dev_json).get(MODELS_DEV_PROVIDER, {}).get("models", {})
    if not known:
        sys.exit(f"models.dev returned no models for {MODELS_DEV_PROVIDER!r}; nothing was changed.")

    files: dict[Path, str] = {}
    positions: list[str] = []
    for model_id in sorted(known):
        meta = known[model_id]
        if meta.get("type") not in MODEL_TYPES:
            print(f"skip  {model_id}: models.dev type {meta.get('type')!r} isn't supported by this plugin")
            continue
        model_type, folder = MODEL_TYPES[meta.get("type")]
        data = BUILDERS[model_type](model_id, meta)
        if meta.get("status") == "deprecated":
            data["deprecated"] = True
        files[args.plugin_dir / "models" / folder / f"{model_id}.yaml"] = dump(data)
        if model_type == "llm":
            positions.append(model_id)

    files[args.plugin_dir / "models" / "llm" / "_position.yaml"] = yaml.safe_dump(positions)

    # Remove files this script generated earlier for models that are gone.
    for folder in {folder for _, folder in MODEL_TYPES.values()}:
        for path in (args.plugin_dir / "models" / folder).glob("*.yaml"):
            if path not in files and path.read_text().startswith(GENERATED_HEADER):
                print(f"remove {path.relative_to(args.plugin_dir)}")
                if not args.dry_run:
                    path.unlink()

    for path, content in files.items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        print(f"{'update' if current else 'create'} {path.relative_to(args.plugin_dir)}")
        if not args.dry_run:
            path.write_text(content)


if __name__ == "__main__":
    main()
